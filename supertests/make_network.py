"""Write supertests/network.py: the d = 2 network of weights/nn_2d_16x2.npz in plain Python,
since Super checks code that uses only the standard library.  Also writes K, the bound on
|logit - slope| that tail.py uses for ||eta|| > 1000.

    python supertests/make_network.py
"""
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
LAM_LO, LAM_HI = 1e-3, 1.5 - 1e-3          # range of lambda in training
C_GELU = np.sqrt(2.0 / np.pi)

z = np.load(os.path.join(HERE, '..', 'weights', 'nn_2d_16x2.npz'))
assert int(z['n_layers']) == 3 and str(z['transform']) == 'loglambda'
W0, W1, W2 = (z[f'W_{i}'] for i in range(3))                  # (4, 16), (16, 16), (16, 1)
B0, B1, B2 = (z[f'b_{i}'] for i in range(3))
mean, std = z['input_mean'], z['input_std']

# K.  GELU(z) = relu(z) + g(z) with |g| <= G, and relu(a + b) is within |b| of relu(a).  The
# first-layer pre-activation is A eta + b1(lambda), with b1 collecting the bias and the
# standardized log lambda and eta means, so layer by layer the logit is within K of
# slope(eta), the same network with relu in place of GELU and every bias dropped.
x = np.linspace(-10.0, 10.0, 2_000_001)
G = np.abs(0.5 * x * (1 + np.tanh(C_GELU * (x + 0.044715 * x ** 3))) - np.maximum(x, 0.0)).max()
assert G < 0.2                              # 0.170 at x = -0.75; |g| < 1e-20 beyond |x| = 10
G = 0.2
lo = np.r_[(np.log(LAM_LO) - mean[:2]) / std[:2], -mean[2:] / std[2:]]
hi = np.r_[(np.log(LAM_HI) - mean[:2]) / std[:2], -mean[2:] / std[2:]]
b1 = np.maximum(np.abs(B0 + np.minimum(lo[:, None] * W0, hi[:, None] * W0).sum(0)),
                np.abs(B0 + np.maximum(lo[:, None] * W0, hi[:, None] * W0).sum(0)))
e1 = b1 + G                                 # first hidden layer: within e1 of relu(A eta)
e2 = np.abs(W1).T @ e1 + np.abs(B1) + G     # second hidden layer
K = float(np.abs(W2[:, 0]) @ e2 + abs(B2[0]))


def literal(a):
    return repr([float(v) for v in a]) if a.ndim == 1 else \
        '[\n' + ''.join(f'    {repr([float(v) for v in row])},\n' for row in a) + ']'


src = f'''"""The d = 2 network h of the paper, for the triangle test, in plain Python.

Generated by supertests/make_network.py from weights/nn_2d_16x2.npz; do not edit.
Same arithmetic as triangle.h: inputs (log lambda, eta) standardized, two GELU layers
(tanh form) and a logistic output.
"""
import math

MEAN = {literal(mean)}
STD = {literal(std)}
W0 = {literal(W0)}
B0 = {literal(B0)}
W1 = {literal(W1)}
B1 = {literal(B1)}
W2 = {literal(W2[:, 0])}
B2 = {float(B2[0])!r}
C_GELU = math.sqrt(2.0 / math.pi)

# |logit(lam1, lam2, eta1, eta2) - slope(eta1, eta2)| <= K for 1e-3 <= lam_i <= 1.499, eta >= 0
K = {K!r}

# eta -> first-layer pre-activation, after standardizing
A = [[W0[2 + k][j] / STD[2 + k] for j in range(16)] for k in range(2)]


def gelu(z):
    return 0.5 * z * (1.0 + math.tanh(C_GELU * (z + 0.044715 * z ** 3)))


def logit(lam1, lam2, eta1, eta2):
    x = [math.log(lam1), math.log(lam2), eta1, eta2]
    s = [(x[k] - MEAN[k]) / STD[k] for k in range(4)]
    h = [gelu(sum(s[k] * W0[k][j] for k in range(4)) + B0[j]) for j in range(16)]
    h = [gelu(sum(h[k] * W1[k][j] for k in range(16)) + B1[j]) for j in range(16)]
    return sum(h[k] * W2[k] for k in range(16)) + B2


def hhat(lam1, lam2, eta1, eta2):
    return 1.0 / (1.0 + math.exp(-logit(lam1, lam2, eta1, eta2)))


def slope(eta1, eta2):
    """The network with relu for GELU and no biases: logit(lambda, t eta) / t -> slope(eta)
    as t -> infinity.  Positively homogeneous of degree 1 in eta."""
    a = [max(0.0, eta1 * A[0][j] + eta2 * A[1][j]) for j in range(16)]
    a = [max(0.0, sum(a[k] * W1[k][j] for k in range(16))) for j in range(16)]
    return sum(a[k] * W2[k] for k in range(16))
'''
with open(os.path.join(HERE, 'network.py'), 'w') as fh:
    fh.write(src)
print(f'wrote supertests/network.py; K = {K:.1f}')
